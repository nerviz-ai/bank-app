package dev.nerviz.bankapp.infrastructure.rest.openapi;

import dev.nerviz.bankapp.infrastructure.rest.dto.AccountResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.enums.ParameterIn;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;
import org.springframework.http.ProblemDetail;

/** Goes on {@code AccountApi#open} alone — {@code @PostMapping} lives on the controller. */
@Target(ElementType.METHOD)
@Retention(RetentionPolicy.RUNTIME)
@Operation(
        summary = "Opens an account for a customer",
        operationId = "openAccount",
        parameters = {
            @Parameter(
                    name = "customerId",
                    in = ParameterIn.PATH,
                    required = true,
                    description = "Customer id as returned by createCustomer",
                    example = "018f9a2e-6b7d-7e2a-9c1f-8a0d5e2b7c11"),
            @Parameter(
                    name = "Idempotency-Key",
                    in = ParameterIn.HEADER,
                    required = true,
                    description = "UUID generated by the client. Repeating the request with the"
                            + " same key returns the stored response.",
                    example = "3fa85f64-5717-4562-b3fc-2c963f66afa6")
        })
@ApiResponse(
        responseCode = "201",
        description = "Account opened. The Location header holds the relative URI of the account",
        content = @Content(schema = @Schema(implementation = AccountResponse.class)))
@ApiResponse(
        responseCode = "400",
        description = "customerId is not a UUID, or the Idempotency-Key header is missing or malformed",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
@ApiResponse(
        responseCode = "401",
        description = "No token, or the token is malformed, expired, or from another issuer or audience",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
@ApiResponse(
        responseCode = "403",
        description =
                "The token carries neither the CUSTOMER nor the OPERATOR role, or a CUSTOMER token has no valid customer id claim",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
@ApiResponse(
        responseCode = "404",
        description = "No such customer, or the customer is not the caller's (errorCode CUSTOMER_NOT_FOUND)",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
@ApiResponse(
        responseCode = "409",
        description =
                "The key was used for another request (errorCode IDEMPOTENCY_KEY_REUSED), or the first request is still in progress (errorCode IDEMPOTENCY_KEY_IN_PROGRESS, with Retry-After)",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
@ApiResponse(
        responseCode = "422",
        description = "The customer is not ACTIVE, or is anonymized (errorCode CUSTOMER_NOT_ELIGIBLE_FOR_ACCOUNT)",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
@ApiResponse(
        responseCode = "500",
        description = "Unmapped error",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
public @interface OpenAccountOpenApiDocs {}
